/** 궁합 지수 구간별 한 줄 코멘트 */
export function scoreBandLabel(score: number): string {
  if (score >= 95) return "환상의 케미";
  if (score >= 85) return "찰떡 케미";
  if (score >= 75) return "좋은 케미";
  return "무난한 케미";
}
